def test_discover_cached_normal_weekends_requires_full_conventional_session_set(
    tmp_path: Path,
) -> None:
    """Only weekends with FP1, FP2, FP3, Q, and R are eligible."""
    normal_dir = tmp_path / "2025" / "2025-04-06_Japanese_Grand_Prix"
    sprint_dir = tmp_path / "2025" / "2025-03-23_Chinese_Grand_Prix"
    for parent, sessions in (
        (
            normal_dir,
            ["Practice_1", "Practice_2", "Practice_3", "Qualifying", "Race"],
        ),
        (
            sprint_dir,
            ["Practice_1", "Sprint_Qualifying", "Qualifying", "Sprint", "Race"],
        ),
    ):
        for index, session_name in enumerate(sessions, start=1):
            session_dir = parent / f"2025-01-0{index}_{session_name}"
            session_dir.mkdir(parents=True)
            (session_dir / "payload.pkl").write_text("cached", encoding="utf-8")

    events = pd.DataFrame(
        [
            {"year": 2025, "race_name": "Japanese Grand Prix"},
            {"year": 2025, "race_name": "Chinese Grand Prix"},
        ]
    )

    discovered = discover_cached_normal_weekends(events=events, cache_dir=tmp_path)

    assert discovered.loc[
        discovered["race_name"].eq("Japanese Grand Prix"), "is_normal_weekend"
    ].iloc[0]
    assert not discovered.loc[
        discovered["race_name"].eq("Chinese Grand Prix"), "is_normal_weekend"
    ].iloc[0]


def test_weekend_profile_scores_blend_sessions_and_pivot() -> None:
    """Session profile scores become one weighted weekend row per team."""
    scores = aggregate_weekend_profile_scores(
        year=2025,
        race_name="Example GP",
        session_scores={
            "FP1": {
                "balanced": {"Fast": 1.0},
                "short_run": {"Fast": 0.8},
                "long_run": {"Fast": 0.4},
            },
            "FP2": {
                "balanced": {"Fast": 0.5},
                "short_run": {"Fast": 0.7},
                "long_run": {"Fast": 0.6},
            },
            "FP3": {
                "balanced": {"Fast": 0.0},
                "short_run": {"Fast": 0.6},
                "long_run": {"Fast": 0.8},
            },
        },
        session_weights={"FP1": 1.0, "FP2": 1.0, "FP3": 2.0},
    )
    pivoted = pivot_weekend_profile_scores(scores)
    row = pivoted.iloc[0]

    assert row["practice_signal_balanced"] == pytest.approx(0.375)
    assert row["practice_signal_short_run"] == pytest.approx(0.675)
    assert row["practice_signal_long_run"] == pytest.approx(0.65)
    assert row["n_sessions_balanced"] == 3


