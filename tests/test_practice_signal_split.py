def test_evaluate_policies_finds_split_when_targets_depend_on_different_profiles() -> None:
    """The split policy wins when quali and race are generated by different signals."""
    rows: list[dict[str, object]] = []
    for year in (2022, 2023, 2024, 2025):
        for index, (short_signal, long_signal) in enumerate(
            ((0.1, 0.8), (0.3, 0.6), (0.7, 0.4), (0.9, 0.2)),
            start=1,
        ):
            driver = f"D{index}"
            rows.extend(
                [
                    {
                        "year": year,
                        "race_name": f"Round {year}",
                        "team": f"Team {index}",
                        "driver_code": driver,
                        "session_kind": "qualifying",
                        "practice_signal_balanced": (short_signal + long_signal) / 2,
                        "practice_signal_short_run": short_signal,
                        "practice_signal_long_run": long_signal,
                        "driver_rating_mu_s": 0.0,
                        "team_target_s": 2.0 * (short_signal - 0.5),
                        "observed_driver_to_field_s": 2.0 * (short_signal - 0.5),
                    },
                    {
                        "year": year,
                        "race_name": f"Round {year}",
                        "team": f"Team {index}",
                        "driver_code": driver,
                        "session_kind": "race",
                        "practice_signal_balanced": (short_signal + long_signal) / 2,
                        "practice_signal_short_run": short_signal,
                        "practice_signal_long_run": long_signal,
                        "driver_rating_mu_s": 0.0,
                        "team_target_s": 2.0 * (long_signal - 0.5),
                        "observed_driver_to_field_s": 2.0 * (long_signal - 0.5),
                    },
                ]
            )

    evaluation = evaluate_practice_signal_policies(pd.DataFrame(rows))
    comparison = evaluation["comparison_vs_best_shared"]
    combined = comparison[comparison["session_kind"].eq("combined")]

    assert combined["split_wins"].all()
    assert combined["delta_mse_s2"].lt(0.0).all()


def test_compare_split_to_best_shared_uses_foldwise_best_single_signal() -> None:
    """The comparison table uses the lowest-MSE shared policy per fold."""
    fold_metrics = pd.DataFrame(
        [
            {
                "policy": "shared_balanced",
                "session_kind": "combined",
                "holdout_year": 2025,
                "mse_s": 0.5,
            },
            {
                "policy": "shared_short_run",
                "session_kind": "combined",
                "holdout_year": 2025,
                "mse_s": 0.3,
            },
            {
                "policy": "shared_long_run",
                "session_kind": "combined",
                "holdout_year": 2025,
                "mse_s": 0.4,
            },
            {
                "policy": "split_short_quali_long_race",
                "session_kind": "combined",
                "holdout_year": 2025,
                "mse_s": 0.2,
            },
        ]
    )

    comparison = compare_split_to_best_shared(fold_metrics)

    assert comparison.iloc[0]["best_shared_policy"] == "shared_short_run"
    assert comparison.iloc[0]["delta_mse_s2"] == pytest.approx(-0.1)


def test_summarize_weighted_policy_metrics_uses_row_counts() -> None:
    """Aggregate policy MSE weights larger held-out folds more heavily."""
    summary = summarize_weighted_policy_metrics(
        pd.DataFrame(
            [
                {
                    "policy": "shared_long_run",
                    "session_kind": "combined",
                    "n_rows": 10,
                    "mse_s": 1.0,
                },
                {
                    "policy": "shared_long_run",
                    "session_kind": "combined",
                    "n_rows": 30,
                    "mse_s": 0.0,
                },
            ]
        )
    )

    assert summary.iloc[0]["weighted_mse_s2"] == pytest.approx(0.25)
    assert summary.iloc[0]["weighted_rmse_s"] == pytest.approx(0.5)
